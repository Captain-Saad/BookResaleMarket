from typing import Protocol


class PhotoStorage(Protocol):
    async def upload_url(self, path: str) -> str | None: ...
    async def download(self, path: str, limit: int) -> bytes: ...
    async def store(self, path: str, data: bytes, content_type: str) -> None: ...
    async def delete(self, path: str) -> None: ...
    async def read_url(self, path: str) -> str | None: ...


class ImageScanner(Protocol):
    async def scan(self, data: bytes) -> bool: ...


class DevelopmentImageScanner:
    async def scan(self, data: bytes) -> bool:
        return True
